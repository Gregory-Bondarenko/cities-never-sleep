def region_of(oktmo) -> str | None:
    """Субъект РФ по коду ОКТМО; None, если код пустой или неизвестен."""
    if oktmo is None or pd.isna(oktmo):
        return None
    s = str(oktmo)
    if len(s) < 2 or not s[:2].isdigit():
        return None
    return REGIONS_3.get(s[:3]) or REGIONS_2.get(s[:2])


